/*
===========================================================
ONLINE RETAIL SALES ANALYSIS
===========================================================

Analysis Area:
Customer Analysis

Objective:
Understand the customer base, customer revenue contribution,
high-value customers, order frequency, and repeat customers.

Source Table:
online_retail_db.clean_sales_data

Business Definitions:
- Customer = Unique non-null CustomerID
- Order = Unique InvoiceNo
- Revenue = Quantity * UnitPrice
- Repeat Customer = Customer with more than 1 unique order

===========================================================
*/

USE online_retail_db;


/*
===========================================================
Q1. How many unique customers are there?
===========================================================
*/

SELECT
    COUNT(DISTINCT CustomerID) AS total_customers
FROM clean_sales_data
WHERE CustomerID IS NOT NULL;


/*
===========================================================
Q2. How much revenue is generated by identified customers?
===========================================================
*/

SELECT
    SUM(Revenue) AS customer_generated_revenue
FROM clean_sales_data
WHERE CustomerID IS NOT NULL;


/*
===========================================================
Q3. Who are the Top 10 Customers by Revenue?
===========================================================
*/

SELECT
    CustomerID,
    SUM(Revenue) AS total_revenue
FROM clean_sales_data
WHERE CustomerID IS NOT NULL
GROUP BY CustomerID
ORDER BY total_revenue DESC
LIMIT 10;


/*
===========================================================
Q4. Who are the Top 10 Customers by Number of Orders?
===========================================================
*/

SELECT
    CustomerID,
    COUNT(DISTINCT InvoiceNo) AS total_orders
FROM clean_sales_data
WHERE CustomerID IS NOT NULL
GROUP BY CustomerID
ORDER BY total_orders DESC
LIMIT 10;



/*
===========================================================
Q5. What is the average revenue generated per customer?
===========================================================
*/

SELECT
    SUM(Revenue) / COUNT(DISTINCT CustomerID) AS average_revenue_per_customer
FROM clean_sales_data
WHERE CustomerID IS NOT NULL;



/*
===========================================================
Q6. How many repeat customers are there?
===========================================================
*/

SELECT
    COUNT(*) AS repeat_customers
FROM (
    SELECT
        CustomerID,
        COUNT(DISTINCT InvoiceNo) AS total_orders
    FROM clean_sales_data
    WHERE CustomerID IS NOT NULL
    GROUP BY CustomerID
    HAVING COUNT(DISTINCT InvoiceNo) > 1
) AS customer_orders;
